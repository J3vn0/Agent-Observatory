export const dictionary: Record<Language, DictionaryShape> = { ko, en };

export type TranslationSection = keyof DictionaryShape;
export type TranslationKey<Section extends TranslationSection> =
  keyof DictionaryShape[Section];

type TranslationParams = Readonly<Record<string, string | number>>;

export function t<
  Section extends TranslationSection,
  Key extends TranslationKey<Section>,
>(
  language: Language,
  section: Section,
  key: Key,
  params?: TranslationParams,
): string {
  const template = dictionary[language][section][key] as string;

  if (!params) {
    return template;
  }

  return template.replace(/\{\{(\w+)\}\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name)
      ? String(params[name])
      : match,
  );
}

export interface LocalizedNodeText {
  label: string;
  summary: string;
}

export function getLocalizedNodeText(
  node: GraphNode,
  language: Language,
): LocalizedNodeText {
  return {
    label: node.localized?.label?.[language] ?? node.label,
    summary: node.localized?.summary?.[language] ?? node.summary,
  };
}
